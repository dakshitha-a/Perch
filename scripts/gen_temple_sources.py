"""Write the "Temple award pages" table in docs/SOURCES.md (REBUILD_PLAN Phase 4 task 7).

One row per page in data/temple/inventory.csv: url, owner, and whether the reader fetched it
or skipped it, and why. "Fetched" comes from the reader's manifest in the page cache
(data/cache/temple_pages/manifest.jsonl, gitignored, so pass --cache-dir from the checkout
that holds it); without a manifest, an eligible row shows as "eligible, no fetch record".

  uv run python scripts/gen_temple_sources.py --cache-dir data/cache/temple_pages
  uv run python scripts/gen_temple_sources.py --check     # exit 1 when the table is stale

The table sits between two HTML comment markers; everything outside them is untouched.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from perch.sources.temple_pages import INVENTORY, read_inventory, skip_reason

DOC = Path("docs/SOURCES.md")
BEGIN = "<!-- BEGIN temple-pages-table (generated by scripts/gen_temple_sources.py) -->"
END = "<!-- END temple-pages-table -->"
WHY = {
    "sign_in_required_or_unknown": "skipped: needs sign-in or the inventory could not tell",
    "robots_not_allowed_or_unknown": "skipped: robots.txt does not allow it, or unknown",
    "no_http_200_in_inventory": "skipped: the inventory has no http 200 (listed from a sitemap)",
}


def _cell(s: str) -> str:
    return s.replace("|", "%7C").replace("\n", " ").strip()


def read_manifest(cache_dir: Path | None) -> dict[str, dict]:
    if cache_dir is None or not (cache_dir / "manifest.jsonl").is_file():
        return {}
    rows = [json.loads(ln) for ln in (cache_dir / "manifest.jsonl").read_text("utf-8")
            .splitlines() if ln.strip()]
    return {r["url"]: r for r in rows}


def status(row: dict, manifest: dict[str, dict]) -> str:
    why = skip_reason(row)
    if why:
        return WHY.get(why, f"skipped: {why}")
    m = manifest.get(row["url"])
    if m:
        return f"fetched {m['fetched_at'][:10]}"
    return "eligible, no fetch record" if not manifest else "eligible, not fetched (failed)"


def table(rows: list[dict], manifest: dict[str, dict]) -> str:
    fetched = sum(status(r, manifest).startswith("fetched") for r in rows)
    lines = [BEGIN, "",
             f"{len(rows)} inventoried pages; {fetched} fetched by the reader. Owner and URL are "
             "as the inventory records them.", "",
             "| URL | Owner | Reader result |", "| --- | --- | --- |"]
    for r in sorted(rows, key=lambda r: r["url"]):
        lines.append(f"| {_cell(r['url'])} | {_cell(r['owner'])} | {status(r, manifest)} |")
    lines += ["", END]
    return "\n".join(lines)


def table_rows(doc: str) -> set[tuple[str, str]]:
    """(url, owner) of every row in the generated table; the reader result is not compared,
    because it depends on a cache that only one checkout holds."""
    if BEGIN not in doc or END not in doc:
        return set()
    body = doc[doc.index(BEGIN):doc.index(END)]
    out = set()
    for ln in body.splitlines():
        cells = [c.strip() for c in ln.strip().strip("|").split(" | ")]
        if ln.startswith("| http") and len(cells) == 3:
            out.add((cells[0], cells[1]))
    return out


def render(doc: str, tbl: str) -> str:
    if BEGIN in doc and END in doc:
        a, b = doc.index(BEGIN), doc.index(END) + len(END)
        return doc[:a] + tbl + doc[b:]
    return doc.rstrip("\n") + "\n\n### Every inventoried page (S40)\n\n" + tbl + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--inventory", default=str(INVENTORY))
    p.add_argument("--cache-dir", default=None)
    p.add_argument("--doc", default=str(DOC))
    p.add_argument("--check", action="store_true")
    a = p.parse_args(argv)
    rows = read_inventory(Path(a.inventory))
    manifest = read_manifest(Path(a.cache_dir) if a.cache_dir else None)
    doc = Path(a.doc)
    new = render(doc.read_text("utf-8"), table(rows, manifest))
    if a.check:
        if table_rows(doc.read_text("utf-8")) != {(_cell(r["url"]), _cell(r["owner"]))
                                                  for r in rows}:
            print(f"{doc} is out of step with the inventory; run scripts/gen_temple_sources.py",
                  file=sys.stderr)
            return 1
        return 0
    doc.write_text(new, encoding="utf-8")
    print(f"Wrote {len(rows)} rows to {doc}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
